// STAGE 1 の地図を組み立てて src/game/stages/stage1.ts を書き出す（企画書 第4.2節「STAGE 1：家の前の路地と公園」）
//   node tools/stagegen/stage1.ts          所要時間を表示するだけ（SHOW=1 で地図も表示）
//   node tools/stagegen/stage1.ts --write  src/game/stages/stage1.ts を上書きする
//
// 作業座標：x＝横、y＝進む向き（y が大きいほどスタート側）。そのまま -y へ登る（画面では右上へ）。
// 地図は企画のときのマス目の定義（2026-10-31）を移したもの。危険物・得点の値・小物の絵はここで決めている。
import { build, Layout, report, write, type P } from './lib.ts';

const BPM = 112;
const BARS = Number(process.env.BARS ?? 41);
const L = new Layout(46, 51);

// ── 安全な道：玄関 → 十字路① → 路地の街区 → 十字路② → 東の通り → 帰り道 → 塀沿い → 玄関
const EAST: P[] = [[32, 25], [42, 25], [42, 22], [45, 22], [45, 14], [42, 14], [42, 10]];
const SAFE: P[] = [[12, 49], [12, 44], [26, 44], [26, 39], [32, 39], [32, 46], [39, 46], [39, 35], [31, 35], [31, 25], ...EAST,
  [30, 10], [30, 8], [22, 8], [22, 10], [9, 10], [9, 5], [14, 5], [14, 0], [3, 0], [3, 3], [6, 3], [6, 4]];
L.path(SAFE, '.');
L.put('S', [12, 49]);
L.seg([6, 5], [6, 5], '.');
L.put('G', [6, 5]);
L.thing('entrance', [11, 49]);

// ── 十字路①（3×3 の交差点、カーブミラー）。西は他家の戸口と得点の行き止まり
L.seg([11, 44], [6, 44], '.');
L.rect(11, 43, 13, 45, '.');
L.thing('mirror', [14, 42]);
L.thing('door', [5, 44]);

// ── 路地の街区：まっすぐ北へ抜ける道が安全な道。南へ回り込む輪は、得点のある八分の寄り道（奥に塀に立てかけた竹ぼうき）
L.seg([32, 36], [32, 38], '.');
for (const [x, y] of [...range(40, 46).map((yy) => [32, yy]), ...range(33, 38).map((xx) => [xx, 46]), ...range(35, 46).map((yy) => [39, yy]), ...range(33, 38).map((xx) => [xx, 35])] as P[]) {
  L.seg([x, y], [x, y], ',');
}
L.seg([36, 47], [36, 49], ',');
L.thing('broom', [35, 47]);
L.thing('house', [28, 41], [29, 42], [35, 41], [35, 43], [34, 37], [36, 33], [33, 31], [28, 33]);
// 戸は道に面する側（手前の2面のどちらか）に置く。道の奥側に置くと、戸が闇を向いて見える
L.thing('door', [31, 46], [38, 36], [41, 23]);

// ── 公園（八分）：子らの足場に沿って十字路②へ合流する。こちらの空の箱ブランコが揺れる
L.path([[12, 43], [12, 37], [9, 37], [9, 32], [13, 32], [13, 28], [10, 28], [10, 26]], ',');
L.seg([10, 25], [30, 25], '.');
L.thing('swingframe', [11, 38], [8, 34], [12, 30], [11, 29]);
// 箱ブランコ（企画書 第4.2節）：近道の道筋に沿って座席が往復する。周期は拍の倍数を避け、振り切ると道の外に出る。
// 座席はプレイヤー（八分）より遅くする（周期 > 4π × 振れ幅）。座席が手前へ振り切ったのを見送ってから歩き出せば、
// 戻ってくる座席に後ろから追いつかれない
const swing = (cells: P[], axis: 'x' | 'y', reach: number, period: number) => L.hazard({ type: 'swing', cells, axis, reach, period });
swing([[9, 37], [10, 37], [11, 37], [12, 37]], 'x', 3, 42);
swing([[9, 33], [9, 34], [9, 35]], 'y', 2.5, 38);
swing([[13, 29], [13, 30], [13, 31]], 'y', 2.5, 34);
swing([[10, 28], [11, 28], [12, 28]], 'x', 2.5, 36);
// 公園の向こう半分（闇で割れている）：上手でブランコをこぐ子と、足もとに脱いだサンダル。空のブランコの枠
L.thing('swingframe', [17, 37], [17, 34], [17, 30]);
L.thing('kid_swing', [19, 32]);
L.thing('kid_sandal', [20, 33]);

// ── 十字路②から北へ：伝聞の大通り（八分）。話に尾ひれがついたような巨大な回旋塔
L.seg([31, 24], [31, 20], ',');
L.rect(8, 17, 36, 19, ',');
L.seg([37, 18], [44, 18], ',');
L.remove(19, 18); // 回旋塔の柱
L.hazard({ type: 'patrol', look: 'kaisento', pivot: [19, 18], waypoints: [[17, 17], [21, 17], [21, 19], [17, 19]], loop: true, interval: 3 });
// ── 北の抜け道（十六分、小節ゲート）：時間の賭け
L.path([[24, 16], [24, 15], [35, 15], [35, 13], [26, 13], [26, 11], [20, 11]], ':');
L.put('B', [29, 15]);
L.hole([35, 16], [35, 12], [25, 14], [26, 10]);
// ── 心細い道（十六分、停止マスと欠け）：得点の賭け。「遠く」の輪郭がいちばん近く見える
L.path([[8, 16], [8, 14], [4, 14], [4, 11], [7, 11], [7, 9], [4, 9], [4, 7], [8, 7]], ':');
L.put('P', [5, 14], [4, 12], [6, 11], [6, 9], [6, 7], [8, 16], [6, 14], [4, 10], [7, 9]);
L.hole([9, 15], [3, 13], [6, 10], [6, 8]);
L.thing('faraway', ...range(6, 16).flatMap((y) => [[0, y], [1, y]] as P[]));

// ── 帰り道 → 塀沿い → 玄関：横の足場を、家へ帰る子が1人歩いている
L.thing('door', [27, 7], [14, 9]);
L.thing('kid_walk', [27, 2]);
L.thing('house', [8, 2], [10, 2], [12, 2]);

// ── 得点：区分けごとに候補の一部がプレイごとに選ばれる
L.score('home', [6, 44], [39, 41], [35, 46], [36, 48], [36, 49]);
L.score('park', [9, 37], [13, 29], [10, 27], [16, 25]);
L.score('avenue', [28, 18], [11, 18], [39, 18]);
L.score('north', [31, 15], [28, 13]);
L.score('narrow', [8, 15], [7, 14], [4, 13], [5, 11], [7, 10], [5, 9], [4, 8], [7, 7]);

// ── 時間帯（場所ごとの置き分け）。境目は目印の場所にそろえる
const band = (_x: number, y: number) => (y >= 34 ? 'n' : y >= 17 ? 'a' : 'd');

// ── 区間の変わり目の小物、全ステージを通すモチーフ（窓・灯り・子どもの履き物）
L.thing('laundry_line', [30, 32]);
L.thing('umbrella_stand', [30, 28]);
L.thing('sign_old', [30, 30]);
L.thing('kite_on_wire', [42, 16]);
L.thing('bucket_water', [42, 15]);
L.thing('home_window', [3, 5]);
L.thing('gate_lamp', [4, 4]);
// 安全な道を8拍進むごとに1本ずつ通り過ぎる街灯。日没前の区間では消えている
// 玄関（ゴール）のまわりは門灯が照らすので、街灯を立てない（ゴールの光の柱に重なって見分けにくくなる）
const lamps: P[] = [[11, 46], [19, 43], [25, 43], [30, 38], [30, 34], [30, 26], [38, 24], [43, 21], [44, 16], [41, 11], [35, 9], [29, 7], [21, 9], [15, 9], [8, 8], [13, 4], [10, 1], [4, 1]];
for (const p of lamps) L.thing(band(...p) === 'd' ? 'lamp_off' : 'lamp', p);

const def = build(L, {
  name: 'STAGE1',
  theme: 'alley',
  bpm: BPM,
  bars: BARS,
  scores: {
    home: { value: 150, decay: 1, pick: 3 },
    park: { value: 250, decay: 2, pick: 3 },
    avenue: { value: 350, decay: 2, pick: 2 },
    north: { value: 500, decay: 3 },
    narrow: { value: 250, decay: 2, pick: 6 },
  },
  floorOf: (x, y) => {
    const k = L.at(x, y)?.k;
    if (k === ',' && x <= 13 && y >= 26 && y <= 43) return 'd';
    if (y >= 17 && y <= 19 && k !== '.') return 'a';
    return 'l';
  },
  tintOf: band,
});
report(def);
write(
  def,
  'stage1',
  'stage1',
  `
STAGE 1 ｜ 入口：玄関 ｜ 家の前の路地と公園（企画書 第4.2節。確定）

昼に玄関を出て、日没前に灯りのついた玄関へ帰る一日。曲の終わりが門限で、安全な道だけだと門限ぎりぎりに帰り着く。
- 景色の薄さは、家がどう知っていたかで決まる。直接見た路地は安全、塀越しの公園は八分、伝聞でしか知らない大通りは八分、その先の抜け道と心細い道は十六分。
- 時間帯は場所で置き分ける（tints）。昼（玄関、十字路①、公園の下半分、路地の街区）、午後（公園の上半分、十字路②、大通り）、日没前（抜け道より先と帰り道）。
- 十字路①で公園の近道か路地の街区か。大通りの先で、北の抜け道（小節ゲート、時間の賭け）か心細い道（停止マスと欠け、得点の賭け）か。帰り道で全員が合流する。
- 危険物は公園の空の箱ブランコと、大通りの巨大な回旋塔。安全な道には危険物も欠けもない。
- 人影は2（公園の向こう半分でブランコをこぐ子、帰り道の横の足場を歩く子）。どちらも渡れない場所にいる。
- 得点マスは区分けごとに、候補の一部がプレイのたびに選ばれる（企画書 第2.3節）。
`,
);

function range(a: number, b: number): number[] {
  return Array.from({ length: b - a + 1 }, (_, i) => a + i);
}
