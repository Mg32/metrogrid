const mirror = (rows: string[]) => rows.map((r) => [...r].reverse().join(''));
/** 向きごとのヘッドホン */
const HEADPHONES = [HEADPHONES_LEFT[0], mirror(HEADPHONES_LEFT[0]), HEADPHONES_LEFT[1], mirror(HEADPHONES_LEFT[1])];

/** 頭（髪の上の方）の位置が立ちのコマからどれだけずれているか。歩きのコマは頭が上下左右に動く */
function headOffset(stand: string[], frame: string[]): { dx: number; dy: number } {
  const hair = (rows: string[], x: number, y: number) => rows[y]?.[x] === 'H';
  let best = { dx: 0, dy: 0, score: -Infinity };
  for (let dy = -3; dy <= 3; dy++) {
    for (let dx = -3; dx <= 3; dx++) {
      let score = 0;
      for (let y = 2; y < 8; y++) {
        for (let x = 0; x < stand[y].length; x++) {
          if (hair(stand, x, y)) score += hair(frame, x + dx, y + dy) ? 1 : -1;
        }
      }
      if (score > best.score) best = { dx, dy, score };
    }
  }
  return best;
}

function withHeadphones(rows: string[], phones: string[], dx: number, dy: number): string[] {
  const out = rows.map((r) => [...r]);
  phones.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      const ty = y + dy;
      const tx = x + dx;
      if (c !== '.' && out[ty]?.[tx] !== undefined) out[ty][tx] = c;
    }
  });
  return out.map((r) => r.join(''));
}

/** [向き][コマ] の行データ（ヘッドホン付き） */
export const GIRL_FRAMES: string[][][] = REF_FRAMES.map((frames, dir) =>
  frames.map((rows) => {
    const { dx, dy } = headOffset(frames[0], rows);
    return withHeadphones(rows, HEADPHONES[dir], dx, dy);
  }),
);

